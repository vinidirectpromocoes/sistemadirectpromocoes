create function direct_private.guard_invoice_review() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if (new.conferencia,new.conferencia_responsavel,new.conferencia_motivo,new.conferencia_em) is distinct from (old.conferencia,old.conferencia_responsavel,old.conferencia_motivo,old.conferencia_em) then
  if new.status='cancelada' or new.conferencia='pendente' or length(btrim(new.conferencia_responsavel))<2 or (new.conferencia='contestada' and length(btrim(new.conferencia_motivo))<5) then raise exception 'Informe responsável e motivo da contestação.'; end if; new.conferencia_em:=now();
 end if;
 return new;
end $$;
