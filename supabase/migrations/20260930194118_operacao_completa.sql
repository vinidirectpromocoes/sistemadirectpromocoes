revoke execute on function direct_private.guard_invoice_review() from public,anon,authenticated;
create function public.direct_review_invoice(p_id bigint,p jsonb) returns void language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or coalesce(direct_private.member_role(),'') not in ('admin','financeiro') then raise exception 'Sem permissão para conferir cobrança.'; end if;
 if p->>'conferencia' not in ('conferida','contestada') then raise exception 'Selecione conferida ou contestada.'; end if;
 update public.cobrancas set conferencia=p->>'conferencia',conferencia_responsavel=coalesce(p->>'responsavel',''),conferencia_motivo=coalesce(p->>'motivo','') where id=p_id and status<>'cancelada';
 if not found then raise exception 'Cobrança não encontrada ou cancelada.'; end if;
end $$;
revoke execute on function public.direct_review_invoice(bigint,jsonb) from public,anon; grant execute on function public.direct_review_invoice(bigint,jsonb) to authenticated;

