create function direct_private.guard_operation_metadata() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if tg_op='INSERT' then
  new.confirmacao := 'aguardando'; new.confirmacao_em:=null; new.confirmacao_por:=null;
  new.loja_validacao:='pendente'; new.loja_responsavel:=''; new.loja_observacao:=''; new.chegada_em:=null; new.saida_em:=null;
  new.loja_validada_em:=null; new.loja_validada_por:=null;
 else
  if (new.confirmacao,new.confirmacao_em,new.confirmacao_por) is distinct from (old.confirmacao,old.confirmacao_em,old.confirmacao_por) then
   if new.status<>'escalada' then raise exception 'Confirmação disponível apenas antes da presença/falta.'; end if;
   new.confirmacao_em:=now(); new.confirmacao_por:=(select auth.jwt()->>'email');
  end if;
  if (new.chegada_em,new.saida_em,new.loja_validacao,new.loja_responsavel,new.loja_observacao,new.loja_validada_em,new.loja_validada_por)
   is distinct from (old.chegada_em,old.saida_em,old.loja_validacao,old.loja_responsavel,old.loja_observacao,old.loja_validada_em,old.loja_validada_por) then
   if new.status<>'presente' or new.loja_validacao='pendente' or length(btrim(new.loja_responsavel))<2 then raise exception 'Confirme a presença e informe o responsável da loja.'; end if;
   if new.loja_validacao='divergencia' and length(btrim(new.loja_observacao))<5 then raise exception 'Descreva a divergência.'; end if;
   if (new.chegada_em is not null and ((new.chegada_em at time zone 'America/Fortaleza')::date<>new.data or new.chegada_em>now()+interval '1 minute'))
    or (new.saida_em is not null and ((new.saida_em at time zone 'America/Fortaleza')::date<>new.data or new.saida_em>now()+interval '1 minute' or new.chegada_em is null or new.saida_em<new.chegada_em)) then raise exception 'Confira os horários efetivos do dia, sem horários futuros.'; end if;
   new.loja_validada_em:=now(); new.loja_validada_por:=(select auth.jwt()->>'email');
  end if;
  if old.status='presente' and new.status<>'presente' then
   new.loja_validacao:='pendente'; new.loja_validada_em:=null; new.loja_validada_por:=null; new.chegada_em:=null; new.saida_em:=null; new.loja_responsavel:=''; new.loja_observacao:='';
  end if;
 end if;
 return new;
end $$;
create trigger guard_operation_metadata before insert or update on public.pedido_escalas for each row execute function direct_private.guard_operation_metadata();
create function direct_private.guard_occurrence() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.escala_id is not null and not exists(select 1 from public.pedido_escalas where id=new.escala_id and pedido_id=new.pedido_id) then raise exception 'Escala não pertence ao pedido.'; end if;
 if tg_op='INSERT' then new.autor:=(select auth.jwt()->>'email'); new.criado_em:=now(); new.estado:='aberta'; new.resolucao:=''; new.resolvida_em:=null;
 else
  if (new.pedido_id,new.escala_id,new.tipo,new.descricao,new.autor,new.criado_em) is distinct from (old.pedido_id,old.escala_id,old.tipo,old.descricao,old.autor,old.criado_em) then raise exception 'Preserve a ocorrência original. Registre a resolução.'; end if;
  if old.estado='resolvida' or new.estado<>'resolvida' or length(btrim(new.resolucao))<5 then raise exception 'Informe a resolução da ocorrência aberta.'; end if;
  new.resolvida_em:=now();
 end if;
 return new;
end $$;
create trigger guard_occurrence before insert or update on public.ocorrencias for each row execute function direct_private.guard_occurrence();

create function public.direct_create_contract(p jsonb) returns public.contratos language plpgsql security definer set search_path='' as $$
declare v public.contratos; old public.contratos; start_date date:=(p->>'inicio')::date; end_date date:=nullif(p->>'fim','')::date;
begin
 if auth.uid() is null or coalesce(direct_private.member_role(),'') not in ('admin','financeiro') then raise exception 'Sem permissão para contratos.'; end if;
 if start_date is null or (end_date is not null and end_date<start_date) then raise exception 'Confira a vigência.'; end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext((p->>'rede')||'|'||lower(coalesce(p->>'loja',''))||'|'||lower(coalesce(p->>'setor',''))));
 if coalesce(p->>'loja','')<>'' and not exists(select 1 from public.lojas where lower(rede)=lower(p->>'rede') and lower(nome)=lower(p->>'loja')) then raise exception 'Loja não cadastrada nessa rede.'; end if;
 if coalesce(p->>'setor','')<>'' and not exists(select 1 from public.tarifas_setores where lower(setor)=lower(p->>'setor')) then raise exception 'Setor não cadastrado nas configurações.'; end if;
 if nullif(p->>'versao_anterior_id','') is not null then
  select * into old from public.contratos where id=(p->>'versao_anterior_id')::bigint for update;
  if old.id is null or (old.rede,old.loja,old.setor) is distinct from (p->>'rede',coalesce(p->>'loja',''),coalesce(p->>'setor','')) or start_date<=old.inicio then raise exception 'Nova versão deve manter abrangência e começar depois da anterior.'; end if;
  if old.fim is null or old.fim>=start_date then update public.contratos set fim=start_date-1 where id=old.id; end if;
 end if;
 if exists(select 1 from public.contratos where rede=p->>'rede' and lower(loja)=lower(coalesce(p->>'loja','')) and lower(setor)=lower(coalesce(p->>'setor','')) and inicio<=coalesce(end_date,'9999-12-31'::date) and coalesce(fim,'9999-12-31'::date)>=start_date) then raise exception 'Há contrato sobreposto. Use Nova versão.'; end if;
 insert into public.contratos(rede,loja,setor,inicio,fim,valor_recebido_centavos,valor_pago_centavos,prazo_dias,responsavel,contato,regras,versao_anterior_id)
 values(p->>'rede',coalesce(p->>'loja',''),coalesce(p->>'setor',''),start_date,end_date,nullif(p->>'valor_recebido_centavos','')::bigint,nullif(p->>'valor_pago_centavos','')::bigint,coalesce((p->>'prazo_dias')::int,30),coalesce(p->>'responsavel',''),coalesce(p->>'contato',''),coalesce(p->>'regras',''),old.id) returning * into v;
 return v;
end $$;
revoke execute on function public.direct_create_contract(jsonb) from public,anon; grant execute on function public.direct_create_contract(jsonb) to authenticated;

create function direct_private.snapshot_contract() returns trigger language plpgsql security definer set search_path='' as $$
declare c public.contratos;
begin
 new.contrato_id:=null;
 if new.pedido_escala_id is not null then
  select ct.* into c from public.contratos ct join public.pedido_escalas s on s.id=new.pedido_escala_id join public.pedidos p on p.id=s.pedido_id
   where lower(ct.rede)=lower(p.supermercado) and (ct.loja='' or lower(ct.loja)=lower(p.unidade)) and (ct.setor='' or lower(ct.setor)=lower(p.setor)) and ct.inicio<=s.data and (ct.fim is null or ct.fim>=s.data)
   order by (case when ct.loja<>'' then 2 else 0 end+case when ct.setor<>'' then 1 else 0 end) desc,ct.inicio desc,ct.id desc limit 1;
  if c.id is not null then new.contrato_id:=c.id; new.valor_centavos:=coalesce(c.valor_pago_centavos,new.valor_centavos); new.valor_recebido_centavos:=coalesce(c.valor_recebido_centavos,new.valor_recebido_centavos); if new.valor_centavos is not null then new.vencimento_pagamento:=new.data; end if; end if;
 else new.contrato_id:=null;
 end if;
 return new;
end $$;
